"""Assemble ``docs/BENCHMARK_RESULTS.md`` from a full benchmark run
(docs/AEGIS_IMPLEMENTATION_PLAN.md Section 33 -- "a full benchmark run produces
docs/BENCHMARK_RESULTS.md with real measured metrics and limitations").

Runs every named dataset, then writes:

  * a **combined** 16-metric table computed over the union of all runs (maximum
    n), each value with its bootstrap 95% CI and formula;
  * a per-dataset metric breakdown;
  * per-task outcomes;
  * the scoring-model calibration outcome (from ``benchmarks.calibrate``);
  * limitations.

Every number is generated here -- the file carries a ``do not edit by hand``
marker and a regression test (``tests/unit/test_benchmark_results_doc.py``)
recomputes the combined table and fails if the committed file drifts.
"""

from __future__ import annotations

import subprocess
from datetime import datetime, timezone
from pathlib import Path

from benchmarks import REPO_ROOT
from benchmarks import dataset as dataset_mod
from benchmarks.calibrate import calibrate
from benchmarks.metrics import PRICING_TABLE_VERSION, MetricValue, compute_all
from benchmarks.report import _fmt_metric
from benchmarks.runner import run_dataset
from benchmarks.schema import BenchmarkResult

DOC_PATH = REPO_ROOT / "docs" / "BENCHMARK_RESULTS.md"
GENERATED_MARKER = "generated by benchmarks/publish.py"
DEFAULT_DATASETS = ("micro", "seeded")


def _git_head() -> str:
    try:
        out = subprocess.run(
            ["git", "-C", str(REPO_ROOT), "rev-parse", "--short", "HEAD"],
            capture_output=True, text=True, timeout=10,
        )
        return out.stdout.strip() or "unknown"
    except Exception:  # noqa: BLE001
        return "unknown"


def run_all(datasets: tuple[str, ...] = DEFAULT_DATASETS, *, workdir: Path) -> dict[str, BenchmarkResult]:
    out: dict[str, BenchmarkResult] = {}
    for name in datasets:
        out[name] = run_dataset(name, workdir=Path(workdir) / name)
    return out


def _combined(results: dict[str, BenchmarkResult]) -> BenchmarkResult:
    merged = BenchmarkResult(
        dataset="+".join(results),
        provider="mock",
        sandbox_mode="fake",
        dataset_digest="; ".join(
            f"{n}:{dataset_mod.dataset_digest(n)}" for n in results
        ),
        aegis_git_head=_git_head(),
    )
    for res in results.values():
        merged.runs.extend(res.runs)
    return merged


def _metric_table(metrics: list[MetricValue]) -> list[str]:
    rows = ["| # | Metric | Value | n | Formula |", "|---|---|---|---|---|"]
    for m in metrics:
        rows.append(f"| {m.number} | {m.name} | {_fmt_metric(m)} | {m.n} | `{m.formula}` |")
    return rows


def _outcomes_table(res: BenchmarkResult) -> list[str]:
    rows = [
        "| task | type | terminal | pipeline verdict | final verdict | fail→pass | pass→pass kept | repair | scope |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r in res.runs:
        te = r.test_eval
        ftp = "n/a" if not te.fail_to_pass else ("yes" if all(te.fail_to_pass.values()) else "no")
        ptp = "yes" if not te.broke_a_pass_to_pass else "**BROKE**"
        rows.append(
            f"| `{r.task_id}` | {r.task_type} | {r.terminal_state or r.error} | "
            f"{r.pipeline_verdict or '-'} | {r.verification_verdict or '-'} | {ftp} | {ptp} | "
            f"{r.repair_outcome or '-'} | {'violation' if r.scope_violation else 'clean'} |"
        )
    return rows


def render_results_doc(results: dict[str, BenchmarkResult]) -> str:
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    combined = _combined(results)
    combined_metrics = compute_all(combined)
    cal = calibrate(combined)
    total_tasks = len(combined.runs)

    L: list[str] = []
    L.append("# AEGIS Benchmark Results")
    L.append("")
    L.append(
        f"<!-- {GENERATED_MARKER} at {ts}; do not edit by hand. "
        f"Regenerate: `python -m benchmarks publish`. -->"
    )
    L.append("")
    L.append(
        "Traceability: `AEGIS_IMPLEMENTATION_PLAN.md` §33, §6; `docs/METRICS.md`; "
        "`docs/EVAL_HARNESS.md`. **Phase 25 deliverable.**"
    )
    L.append("")
    L.append(f"- **datasets:** {', '.join(f'`{n}` ({len(r.runs)} tasks)' for n, r in results.items())}")
    L.append(f"- **total tasks:** {total_tasks}")
    L.append(f"- **provider:** `mock` · **sandbox:** `fake` · **AEGIS HEAD:** `{combined.aegis_git_head}`")
    L.append(f"- **dataset digests:** `{combined.dataset_digest}`")
    L.append(f"- **generated:** {ts}")
    errored = [r.task_id for r in combined.runs if r.error]
    if errored:
        L.append(f"- **errored tasks:** {', '.join(errored)}")
    L.append("")
    L.append("## 1. Objective metrics — combined (Spec §40)")
    L.append("")
    L.append(f"Computed over the union of all {total_tasks} tasks (maximum n per metric).")
    L.append("")
    L.extend(_metric_table(combined_metrics))
    L.append("")
    m10 = next(m for m in combined_metrics if m.number == 10)
    L.append(
        f"**Headline release gate — false-complete rate (from #10): "
        f"{m10.note.split(';')[0].split('=')[-1].strip()}** (hard ceiling 2%)."
    )
    L.append("")
    for n, res in results.items():
        L.append(f"## 2.{list(results).index(n) + 1} Dataset `{n}`")
        L.append("")
        L.extend(_metric_table(compute_all(res)))
        L.append("")
        L.append(f"### `{n}` per-task outcomes")
        L.append("")
        L.extend(_outcomes_table(res))
        L.append("")
    L.append("## 3. Scoring-model calibration")
    L.append("")
    L.append(f"- **model version:** `{cal['model_version']}` · **action:** `{cal['action']}`")
    L.append(
        f"- **labeled data points:** {cal['labeled_n']} "
        f"(train {cal['train_n']} / held-out {cal['held_out_n']})"
    )
    L.append(
        f"- **confusion (labeled set):** TP {cal['confusion']['tp']}, TN {cal['confusion']['tn']}, "
        f"FP {cal['confusion']['fp']}, FN {cal['confusion']['fn']} · "
        f"false-complete rate {cal['false_complete_rate']}"
    )
    L.append("")
    L.append(cal["conclusion"])
    L.append("")
    L.append("## 4. Limitations")
    L.append("")
    L.append(
        "- **Curated mini-repo fixtures**, not real OSS issues; `MockProvider` (no live "
        "model) and the **fake** sandbox (no Docker). Values are provisional and not "
        "comparable to a live SWE-bench run."
    )
    L.append(
        "- The fake sandbox never executes targeted tests in-stage, so AEGIS never reaches "
        "`VERIFIED` autonomously — every `pipeline verdict` is `PARTIAL`. The harness promotes "
        "a human-approval-gated task to done **only** when the reconstructed workspace passes "
        "the task's `fail_to_pass`/`pass_to_pass` sets (ground truth). This makes a "
        "false-complete structurally impossible here (#10) — a real false-complete rate needs "
        "the live sandbox and a larger labeled set."
    )
    L.append(
        f"- **#13 cost is simulated** — `{PRICING_TABLE_VERSION}` placeholder prices × "
        "approximate `MockProvider` token counts, not live accounting."
    )
    L.append(
        "- **#15 requires reference agents** (OpenHands / Aider) run on the identical task "
        "set in their own containers; none are configured in this environment "
        "(`benchmarks/agents/README.md`)."
    )
    L.append(
        "- **#16 replay fidelity** is `check_reapplies` (1.0/0.0 per task), not a full "
        "recorded-input replay manifest (Phase 20 open item)."
    )
    L.append(
        "- Small deterministic samples → bootstrap CIs are wide or degenerate; treat "
        "single-run values as directional."
    )
    L.append("")
    return "\n".join(L)


def write_results_doc(
    datasets: tuple[str, ...] = DEFAULT_DATASETS, *, workdir: Path, doc_path: Path = DOC_PATH
) -> Path:
    results = run_all(datasets, workdir=workdir)
    doc_path.write_text(render_results_doc(results), encoding="utf-8")
    return doc_path
