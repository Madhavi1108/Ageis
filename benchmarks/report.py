"""Serialize a benchmark run: results.json, results.xlsx, and the Markdown body
of docs/BENCHMARK_RESULTS.md. Numbers are always generated here, never authored
by hand (docs/AEGIS_IMPLEMENTATION_PLAN.md Section 33).
"""

from __future__ import annotations

import json
from pathlib import Path

from openpyxl import Workbook

from app.reporting.styles import autofit, write_header_row
from benchmarks.metrics import MetricValue, compute_all
from benchmarks.schema import BenchmarkResult

GENERATED_MARKER = "generated by benchmarks/report.py"


def _fmt_metric(m: MetricValue) -> str:
    if m.value is None:
        return f"N/A — {m.note or 'no data'}"
    ci = f" (95% CI {m.ci95[0]}–{m.ci95[1]})" if m.ci95 else ""
    return f"{m.value}{ci}"


def render_benchmark_markdown(result: BenchmarkResult, metrics: list[MetricValue]) -> str:
    ts = result.generated_at.strftime("%Y-%m-%dT%H:%M:%SZ")
    lines: list[str] = []
    lines.append("# AEGIS Benchmark Results")
    lines.append("")
    lines.append(
        f"<!-- {GENERATED_MARKER} at {ts} from dataset {result.dataset} "
        f"({result.dataset_digest}); do not edit by hand -->"
    )
    lines.append("")
    lines.append(
        "Traceability: `AEGIS_IMPLEMENTATION_PLAN.md` §33, §6; `docs/METRICS.md`; "
        "`docs/EVAL_HARNESS.md`. Phase 25 deliverable."
    )
    lines.append("")
    lines.append(f"- **dataset:** `{result.dataset}` ({len(result.runs)} tasks)")
    lines.append(f"- **provider:** `{result.provider}` · **sandbox:** `{result.sandbox_mode}`")
    lines.append(f"- **AEGIS HEAD:** `{result.aegis_git_head or 'unknown'}`")
    lines.append(f"- **generated:** {ts}")
    errored = [r.task_id for r in result.runs if r.error]
    if errored:
        lines.append(f"- **errored tasks:** {', '.join(errored)}")
    lines.append("")
    lines.append("## Objective metrics (Spec §40)")
    lines.append("")
    lines.append("| # | Metric | Value | n | Formula |")
    lines.append("|---|---|---|---|---|")
    for m in metrics:
        lines.append(
            f"| {m.number} | {m.name} | {_fmt_metric(m)} | {m.n} | `{m.formula}` |"
        )
    lines.append("")
    fc = next((m for m in metrics if m.number == 10), None)
    if fc and fc.value is not None:
        lines.append(f"**Headline gate — false-complete rate:** see #10 note. Ceiling 2%.")
        lines.append("")
    lines.append("## Per-task outcomes")
    lines.append("")
    lines.append("| task | type | terminal | verdict | fail→pass | pass→pass kept | repair | scope |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for r in result.runs:
        te = r.test_eval
        ftp = "n/a" if not te.fail_to_pass else ("yes" if all(te.fail_to_pass.values()) else "no")
        ptp = "yes" if not te.broke_a_pass_to_pass else "BROKE"
        lines.append(
            f"| `{r.task_id}` | {r.task_type} | {r.terminal_state or r.error} | "
            f"{r.verification_verdict or '-'} | {ftp} | {ptp} | "
            f"{r.repair_outcome or '-'} | {'violation' if r.scope_violation else 'clean'} |"
        )
    lines.append("")
    lines.append("## Limitations")
    lines.append("")
    lines.append(
        "- Curated mini-repo fixtures, not real OSS issues; `MockProvider` (no live model) "
        "and the **fake** sandbox (no Docker). Numbers are provisional and not comparable to a "
        "live SWE-bench run."
    )
    lines.append(
        "- #13 cost is **simulated** — `pricing-table v1.0.0` placeholder prices × approximate "
        "MockProvider token counts."
    )
    lines.append("- #15 requires reference agents (OpenHands / Aider); none are configured here.")
    lines.append(
        "- Small, deterministic samples → bootstrap CIs are wide or degenerate; treat single-"
        "dataset values as directional."
    )
    lines.append(
        "- `scoring-model v1.0.0` is **retained** — `benchmarks/calibrate.py` reports "
        "`INSUFFICIENT_DATA` for a statistically meaningful re-fit on this set."
    )
    lines.append("")
    return "\n".join(lines)


def _metrics_sheet(wb: Workbook, metrics: list[MetricValue]) -> None:
    ws = wb.active
    ws.title = "Metrics"
    write_header_row(ws, ["#", "Metric", "Formula", "Value", "Basis", "n", "CI95", "Note"])
    for m in metrics:
        ws.append([
            m.number, m.name, m.formula,
            "" if m.value is None else m.value,
            m.basis, m.n,
            f"{m.ci95[0]}–{m.ci95[1]}" if m.ci95 else "",
            m.note,
        ])
    autofit(ws)


def _runs_sheet(wb: Workbook, result: BenchmarkResult) -> None:
    ws = wb.create_sheet("Runs")
    write_header_row(ws, [
        "task", "dataset", "type", "terminal", "verdict", "verified_fixed",
        "broke_pass_to_pass", "repair_outcome", "repair_iters", "scope_violation",
        "tests_valid/gen", "ai_calls", "wall_clock_ms", "error",
    ])
    for r in result.runs:
        ws.append([
            r.task_id, r.dataset, r.task_type, r.terminal_state or "", r.verification_verdict or "",
            r.test_eval.verified_fixed, r.test_eval.broke_a_pass_to_pass,
            r.repair_outcome or "", r.repair_iterations, r.scope_violation,
            f"{r.tests_valid}/{r.tests_generated}", len(r.ai_calls), r.wall_clock_ms, r.error or "",
        ])
    autofit(ws)


def write_reports(result: BenchmarkResult, out_dir: Path) -> dict[str, Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    metrics = compute_all(result)

    results_json = out_dir / "results.json"
    results_json.write_text(
        json.dumps(
            {
                "result": result.model_dump(mode="json"),
                "metrics": [m.model_dump() for m in metrics],
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    wb = Workbook()
    _metrics_sheet(wb, metrics)
    _runs_sheet(wb, result)
    results_xlsx = out_dir / "results.xlsx"
    wb.save(results_xlsx)

    summary_md = out_dir / "summary.md"
    summary_md.write_text(render_benchmark_markdown(result, metrics), encoding="utf-8")

    return {"json": results_json, "xlsx": results_xlsx, "markdown": summary_md}
